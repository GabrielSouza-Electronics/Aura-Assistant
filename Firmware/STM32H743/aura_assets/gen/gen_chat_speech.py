"""Convert a 48 kHz mono PCM16 WAV to internal-flash PCM and speech cues.

The envelope describes voiced spans, not linguistic word boundaries. Run:
  python aura_assets/gen/gen_chat_speech.py aura_assets/audio/chat_test.wav
"""
import argparse
import json
from pathlib import Path
import wave
import numpy as np

ROOT = Path(__file__).resolve().parents[2]


def analyze(samples, rate):
    hop = rate // 100  # 10 ms analysis windows
    padded = np.pad(samples.astype(np.float64), (0, (-len(samples)) % hop))
    rms = np.sqrt(np.mean(padded.reshape(-1, hop) ** 2, axis=1))
    threshold = max(100.0, float(np.percentile(rms, 95)) * 0.10)
    voiced = rms >= threshold
    # Fill only short internal gaps; preserve real pauses for Speak Idle.
    i = 0
    while i < len(voiced):
        if voiced[i]:
            i += 1
            continue
        start = i
        while i < len(voiced) and not voiced[i]:
            i += 1
        if start > 0 and i < len(voiced) and i - start <= 3:
            voiced[start:i] = True
    spans = []
    i = 0
    while i < len(voiced):
        if not voiced[i]:
            i += 1
            continue
        start = i
        while i < len(voiced) and voiced[i]:
            i += 1
        if i - start >= 4:
            spans.append((start * hop, min(i * hop, len(samples)), float(np.mean(rms[start:i]))))
    short_levels = [level for start, end, level in spans if end - start < rate * 0.42]
    open_threshold = float(np.median(short_levels)) if short_levels else threshold
    cues = []
    for start, end, level in spans:
        first, last = (23, 37) if end - start >= rate * 0.42 else (
            (14, 23) if level >= open_threshold else (9, 14))
        cues.append(dict(start_sample=start, end_sample=end, first_frame=first, last_frame=last))
    return cues, threshold, open_threshold


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('wav', type=Path)
    args = parser.parse_args()
    with wave.open(str(args.wav), 'rb') as wav:
        if (wav.getframerate(), wav.getnchannels(), wav.getsampwidth()) != (48000, 1, 2):
            parser.error('input must be 48 kHz mono PCM16')
        samples = np.frombuffer(wav.readframes(wav.getnframes()), dtype='<i2')
    if len(samples) == 0:
        parser.error('input is empty')
    cues, threshold, open_threshold = analyze(samples, 48000)
    out = ROOT / 'Components/Audio'
    (out / 'chat_test_audio.h').write_text('''#ifndef CHAT_TEST_AUDIO_H
#define CHAT_TEST_AUDIO_H
#include <stdint.h>
#define CHAT_TEST_SAMPLE_RATE 48000U
''' + f'#define CHAT_TEST_SAMPLE_COUNT {len(samples)}U\n' + '''#ifdef __cplusplus
extern "C" {
#endif
extern const int16_t chat_test_pcm[CHAT_TEST_SAMPLE_COUNT];
#ifdef __cplusplus
}
#endif
#endif
''')
    with (out / 'chat_test_audio.c').open('w') as target:
        target.write('/* Generated by gen_chat_speech.py. Internal flash; no RAM copy. */\n#include "chat_test_audio.h"\nconst int16_t chat_test_pcm[CHAT_TEST_SAMPLE_COUNT] = {\n')
        for start in range(0, len(samples), 16):
            target.write('    ' + ','.join(map(str, samples[start:start + 16])) + ',\n')
        target.write('};\n')
    with (out / 'chat_test_timeline.h').open('w') as target:
        target.write('/* Generated by gen_chat_speech.py. */\n#ifndef CHAT_TEST_TIMELINE_H\n#define CHAT_TEST_TIMELINE_H\n#include "speech_animation.h"\n')
        target.write(f'#define CHAT_TEST_CUE_COUNT {len(cues)}U\nstatic const SpeechCue chat_test_cues[] = {{\n')
        for cue in cues:
            target.write('    {' + ','.join(str(v) + 'U' for v in cue.values()) + '},\n')
        if not cues:
            target.write('    {0U,0U,1U,8U}, /* Empty timeline sentinel, count is zero. */\n')
        target.write('};\n#endif\n')
    report = dict(duration_seconds=len(samples) / 48000, sample_count=len(samples),
                  silence_rms_threshold=threshold, short_open_rms_threshold=open_threshold, cues=cues)
    preview = ROOT / 'aura_assets/preview'
    preview.mkdir(exist_ok=True)
    (preview / 'chat_speech_timeline.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
